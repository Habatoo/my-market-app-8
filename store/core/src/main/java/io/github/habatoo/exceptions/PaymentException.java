package io.github.habatoo.exceptions;

/**
 * Базовое исключение для ошибок, возникающих при выполнении операции оплаты.
 * Используется как общее родительское исключение для бизнес-ошибок сервиса платежей.
 */
public abstract class PaymentException extends RuntimeException {

    /**
     * Ошибка, возникающая в случае недостаточности средств для совершения платежа.
     * Выбрасывается, когда сумма списания превышает текущий баланс,
     * и операция оплаты не может быть завершена.
     */
    public static class InsufficientFunds extends PaymentException {
    }

    /**
     * Ошибка, сигнализирующая о недоступности сервиса платежей.
     * Может возникать при технических сбоях, сетевых ошибках или недоступности внешнего API.
     * Данная ошибка позволяет корректно оповестить пользователя и прервать процесс оформления заказа.
     */
    public static class PaymentServiceUnavailable extends PaymentException {
    }
}
